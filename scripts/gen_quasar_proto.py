def generate_modules(out_dir: Path, proto_dir: Path | None = None) -> list[Path]:
    if proto_dir is not None and proto_dir.exists():
        # Verify canonical `.proto` files exist in the external schema checkout when supplied
        expected = [
            "yandex_io/protos/quasar_proto.proto",
            "yandex_io/protos/remoting.proto",
            "yandex_io/protos/alice_state.proto",
            "yandex_io/protos/yandex_io.proto",
            "yandex_io/protos/model_objects.proto",
        ]
        for rel in expected:
            candidate = proto_dir / rel
            if not candidate.exists():
                raise FileNotFoundError(f"Missing expected schema file: {candidate}")

    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for filename, content in MODULES.items():
        path = out_dir / filename
        header = "#![allow(dead_code)]\n\n"
        path.write_text(header + content, encoding="utf-8", newline="\n")
        written.append(path)
    return written


